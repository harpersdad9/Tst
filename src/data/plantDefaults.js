export function getSmartDefaults(speciesOrName) {
  if (!speciesOrName) return null;
  const lower = speciesOrName.toLowerCase().trim();
  // Exact match first
  if (PLANT_DEFAULTS[lower]) return PLANT_DEFAULTS[lower];
  // Partial match
  for (const key of Object.keys(PLANT_DEFAULTS)) {
    if (lower.includes(key) || key.includes(lower)) {
      return PLANT_DEFAULTS[key];
    }
  }
  return null;
}

